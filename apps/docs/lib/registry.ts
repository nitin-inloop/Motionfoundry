import registryJson from "../../../registry/registry.json";

export type ControlDef =
  | { prop: string; label: string; type: "text" }
  | { prop: string; label: string; type: "range"; min: number; max: number; step: number }
  | { prop: string; label: string; type: "select"; options: string[] }
  | { prop: string; label: string; type: "boolean" }
  | { prop: string; label: string; type: "color" }
  | { prop: string; label: string; type: "list" };

export type PropValue = string | number | boolean | string[];

export interface RegistryFile {
  path: string;
  type: string;
  content: string;
}

export interface RegistryComponent {
  slug: string;
  name: string;
  category: string;
  collection: string;
  featured: boolean;
  addedAt: string;
  version: string;
  requiresMotion: boolean;
  dependencies: string[];
  description: string;
  tags: string[];
  a11yNotes: string;
  defaultProps: Record<string, PropValue>;
  controls: ControlDef[];
  propsApi: { name: string; type: string; default: string; description: string }[];
  files: RegistryFile[];
  tailwindExample: string;
}

export interface RegistryCollection {
  id: string;
  name: string;
  description: string;
  count: number;
}

interface Registry {
  version: string;
  categories: string[];
  collections: RegistryCollection[];
  components: RegistryComponent[];
}

// registry.json is generated by scripts/build-registry.mjs, which validates this shape.
const registryData = registryJson as unknown as Registry;

export function getAllComponents(): RegistryComponent[] {
  return registryData.components;
}

export function getComponentBySlug(slug: string): RegistryComponent | undefined {
  return registryData.components.find((c) => c.slug === slug);
}

export function getCategories(): string[] {
  return registryData.categories;
}

export function getCollections(): RegistryCollection[] {
  return registryData.collections;
}

export function getCollection(id: string): RegistryCollection | undefined {
  return registryData.collections.find((c) => c.id === id);
}

export function getComponentsByCollection(id: string): RegistryComponent[] {
  return registryData.components.filter((c) => c.collection === id);
}

export { NEW_VERSION, NEW_VERSION_LABEL, isNewComponent } from "./catalog-filters";

export function getRegistryVersion(): string {
  return registryData.version;
}

/** Registry entries without source code — small enough to hand to client-side catalog views. */
export type CatalogComponent = Pick<
  RegistryComponent,
  "slug" | "name" | "category" | "collection" | "description" | "tags" | "defaultProps" | "featured" | "version" | "requiresMotion" | "addedAt"
>;

export function toCatalog(components: RegistryComponent[]): CatalogComponent[] {
  return components.map(({ slug, name, category, collection, description, tags, defaultProps, featured, version, requiresMotion, addedAt }) => ({
    slug,
    name,
    category,
    collection,
    description,
    tags,
    defaultProps,
    featured,
    version,
    requiresMotion,
    addedAt,
  }));
}
