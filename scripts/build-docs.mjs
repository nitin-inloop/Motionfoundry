#!/usr/bin/env node
/**
 * Generates apps/docs/lib/docs.ts from apps/docs/content/docs/*.mdx so the MDX files are the
 * single source of truth for documentation copy.
 *
 * Each MDX file is: frontmatter (title, category, summary) → "# Title" → Markdown body → one
 * trailing fenced code block.
 *
 * Usage: node scripts/build-docs.mjs [--check]
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const rootDir = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const contentDir = path.join(rootDir, "apps/docs/content/docs");
const outFile = path.join(rootDir, "apps/docs/lib/docs.ts");
const checkOnly = process.argv.includes("--check");

/** Sidebar order. New pages must be added here. */
const ORDER = [
  "getting-started",
  "installation",
  "using-components",
  "studio-kit",
  "design-systems",
  "gradients-text-scroll",
  "tailwind-setup",
  "css-setup",
  "nextjs-integration",
  "component-api-reference",
  "animation-configuration",
  "customization",
  "accessibility",
  "performance",
  "troubleshooting",
  "contributing",
  "changelog",
  "license",
];

function parse(slug) {
  const raw = fs.readFileSync(path.join(contentDir, `${slug}.mdx`), "utf8").replace(/\r\n/g, "\n");
  const fm = raw.match(/^---\n([\s\S]*?)\n---\n\n# [^\n]+\n\n([\s\S]*)$/);
  if (!fm) throw new Error(`${slug}.mdx: expected frontmatter followed by "# Title"`);
  const meta = Object.fromEntries(
    fm[1].split("\n").map((line) => {
      const [, key, value] = line.match(/^(\w+):\s*"(.*)"$/) ?? [];
      if (!key) throw new Error(`${slug}.mdx: malformed frontmatter line "${line}"`);
      return [key, value.replace(/\\"/g, '"')];
    })
  );
  const rest = fm[2].replace(/\n+$/, "");
  const fenceStart = rest.lastIndexOf("\n\n```");
  if (fenceStart === -1 || !rest.endsWith("```")) throw new Error(`${slug}.mdx: expected a trailing fenced code block`);
  const body = rest.slice(0, fenceStart);
  const code = rest.slice(fenceStart + 2).replace(/^```[^\n]*\n/, "").replace(/\n```$/, "");
  return { slug, title: meta.title, category: meta.category, summary: meta.summary, body, code };
}

const files = fs.readdirSync(contentDir).filter((f) => f.endsWith(".mdx")).map((f) => f.replace(/\.mdx$/, ""));
const unordered = files.filter((f) => !ORDER.includes(f));
const missing = ORDER.filter((f) => !files.includes(f));
if (unordered.length || missing.length) {
  console.error(`[build-docs] ORDER mismatch. Not in ORDER: ${unordered.join(", ") || "-"}; missing files: ${missing.join(", ") || "-"}`);
  process.exit(1);
}

const pages = ORDER.map(parse);
const output = [
  "// Generated by scripts/build-docs.mjs from apps/docs/content/docs/*.mdx — edit the MDX files, not this file.",
  `export const DOCS_PAGES = ${JSON.stringify(pages, null, 2)} as const;`,
  "export function getDocBySlug(slug: string) {",
  "  return DOCS_PAGES.find((d) => d.slug === slug);",
  "}",
  "",
].join("\n");

const current = fs.existsSync(outFile) ? fs.readFileSync(outFile, "utf8") : "";
if (checkOnly) {
  if (current !== output) {
    console.error("[build-docs] apps/docs/lib/docs.ts is out of date (run node scripts/build-docs.mjs)");
    process.exit(1);
  }
} else if (current !== output) {
  fs.writeFileSync(outFile, output, "utf8");
}
console.log(`[build-docs] ${checkOnly ? "Verified" : "Wrote"} ${pages.length} documentation pages.`);
